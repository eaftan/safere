"""Extract pinned Unicode 17 grapheme properties without ICU or SafeRE tables.

Usage: python3 safere-fuzz/scripts/generate-grapheme-reference.py UCD_DIRECTORY
Download auxiliary/GraphemeBreakProperty.txt, DerivedCoreProperties.txt and
emoji/emoji-data.txt from https://www.unicode.org/Public/17.0.0/ucd/ into that
flat directory. Source hashes are pinned below; output is deterministic.
"""

import hashlib
from pathlib import Path
import sys

SOURCES = {
    "GraphemeBreakProperty.txt": "d6b51d1d2ae5c33b451b7ed994b48f1f4dc62b2272a5831e7fd418514a6bae89",
    "DerivedCoreProperties.txt": "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08",
    "emoji-data.txt": "2cb2bb9455cda83e8481541ecf5b6dfda66a3bb89efa3fa7c5297eccf607b72b",
}


def main():
    directory = Path(sys.argv[1])
    properties = [["Other", "None", "N"] for _ in range(0x110000)]
    for name, digest in SOURCES.items():
        raw = (directory / name).read_bytes()
        if hashlib.sha256(raw).hexdigest() != digest:
            raise ValueError(f"Unexpected Unicode 17 source: {name}")
        for line in raw.decode("utf-8").splitlines():
            fields = [part.strip() for part in line.split("#")[0].split(";")]
            if len(fields) < 2:
                continue
            if name == "GraphemeBreakProperty.txt":
                column, value = 0, fields[1]
            elif name == "DerivedCoreProperties.txt" and fields[1] == "InCB":
                column, value = 1, fields[2]
            elif name == "emoji-data.txt" and fields[1] == "Extended_Pictographic":
                column, value = 2, "Y"
            else:
                continue
            bounds = fields[0].split("..")
            for cp in range(int(bounds[0], 16), int(bounds[-1], 16) + 1):
                properties[cp][column] = value
    output = Path(__file__).resolve().parents[1] / (
        "src/test/resources/org/safere/fuzz/grapheme-properties-17.0.0.txt"
    )
    with output.open("w", encoding="utf-8", newline="\n") as out:
        out.write("# Unicode 17.0.0: GCB, InCB, Extended_Pictographic (Y/N)\n")
        out.write("# Generated by scripts/generate-grapheme-reference.py; do not edit.\n")
        out.write("# Copyright Unicode, Inc.; Unicode License V3, see LICENSE-Unicode.txt.\n")
        for name, digest in SOURCES.items():
            out.write(f"# SHA-256 {name}: {digest}\n")
        start = 0
        for end in range(1, len(properties) + 1):
            if end == len(properties) or properties[start] != properties[end]:
                out.write(f"{start:04X}..{end - 1:04X};" + ";".join(properties[start]) + "\n")
                start = end


if __name__ == "__main__":
    main()
